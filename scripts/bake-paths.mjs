import fs from 'node:fs';
import {worldPathLinks} from '../dist/world-paths.js';
import {festivalDestinations} from '../dist/festival-layout.js';
import {findPath} from '../dist/navigation.js';
import {canStandAt} from '../dist/movement.js';
const links=[...worldPathLinks,...festivalDestinations.flatMap(p=>{const points=[[-37,4],...(p.approach||[]),[p.x,p.z]];return points.slice(1).map((b,i)=>[points[i],b,p.approach?2.7:4.8]);})],routes=[];
for(const [a,b,width] of links){const start={x:a[0],z:a[1]},path=findPath(start,{x:b[0],z:b[1]});if(!path.length)throw Error(`Unreachable promenade: ${a} → ${b}`);routes.push({width,points:[a,...path.map(p=>[p.x,p.z])]});}
// Join authored links before rounding: drawing each link independently left a
// sharp elbow at every waypoint, even though each individual path was smooth.
const key=p=>p.map(n=>n.toFixed(3)).join('/'),degree=new Map();
for(const route of routes)for(const p of [route.points[0],route.points.at(-1)])degree.set(key(p),(degree.get(key(p))||0)+1);
for(let i=0;i<routes.length;i++){
 const route=routes[i];let joined=true;
 while(joined){joined=false;for(let j=i+1;j<routes.length;j++){
  const next=routes[j];let points=next.points;
  if(key(route.points.at(-1))===key(points.at(-1)))points=[...points].reverse();
  if(key(route.points.at(-1))!==key(points[0])||degree.get(key(points[0]))!==2)continue;
  route.points.push(...points.slice(1));route.width=Math.min(route.width,next.width);routes.splice(j,1);joined=true;break;
 }}
}
for(const route of routes){
 const points=route.points,rounded=[points[0]];
 for(let i=1;i<points.length-1;i++){
  const a=points[i-1],b=points[i],c=points[i+1],ab=Math.hypot(a[0]-b[0],a[1]-b[1]),bc=Math.hypot(c[0]-b[0],c[1]-b[1]),cut=Math.min(6,ab*.3,bc*.3);
  if(cut<.2){rounded.push(b);continue;}
  const start=b.map((n,j)=>n+(a[j]-n)*cut/ab),end=b.map((n,j)=>n+(c[j]-n)*cut/bc),arc=Array.from({length:13},(_,j)=>{const t=j/12;return b.map((n,k)=>(1-t)**2*start[k]+2*(1-t)*t*n+t*t*end[k]);});
  if(arc.every(([x,z],i)=>{const before=arc[Math.max(0,i-1)],after=arc[Math.min(arc.length-1,i+1)],dx=after[0]-before[0],dz=after[1]-before[1],length=Math.hypot(dx,dz)||1,margin=Math.min(1.1,route.width/2-.25);return [-margin,0,margin].every(side=>canStandAt(x-dz/length*side,z+dx/length*side));}))rounded.push(...arc);else rounded.push(b);
 }
 rounded.push(points.at(-1));route.points=rounded;
}
fs.writeFileSync(new URL('../dist/path-routes.js',import.meta.url),'// Generated by scripts/bake-paths.mjs; the collision model is the source of truth.\nexport const pathRoutes='+JSON.stringify(routes)+';\n');
console.log(`Baked ${routes.length} connected promenades.`);
